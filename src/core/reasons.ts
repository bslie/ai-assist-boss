/**
 * Причины «почему я спрашиваю» для руководителя. В БД и журнале лежат исходные формулировки
 * шлюза (с кодами сигналов) для аудита; на экран и в Telegram идёт этот человеческий текст.
 */

const SIGNALS: Record<string, string> = {
  MANAGER_PARTY: "Пишет или адресовано вышестоящему руководству",
  HR_PARTY: "Пишет HR-партнёр",
  FINANCE_PARTY: "Пишет финансовый контроль",
  HR_TERMS: "Речь о кадровом вопросе: отпуск, найм, увольнение или зарплата",
  COMMITMENT_TERMS: "Внешняя сторона просит обязательство по срокам или условиям",
  MONEY_APPROVAL: "Просят согласовать деньги или скидку",
  EXTERNAL_INVITATION: "Внешнее приглашение выступить или участвовать",
  MONEY_TERMS: "В письме упоминаются деньги",
};

const CATEGORIES: Record<string, string> = {
  HR: "Кадровые вопросы я без вас не решаю",
  MANAGEMENT: "Письма руководству я без вас не отправляю",
  CLIENT_COMMITMENT: "Обещания клиентам даю только с вашего согласия",
  MONEY: "Деньги и бюджеты решаете вы",
  INVITATION: "Приглашения решаете вы",
};

const EXACT: [RegExp, string][] = [
  [/^Категория не определена$/, "Я не поняла, о чём это письмо"],
  [/^Уверенность (?:классификатора )?ниже порога$/, "Я не уверена, как это письмо разобрать"],
  [/^Деньги в исходящем действии$/, "Ответ затрагивает деньги"],
  [/^Затронут защищённый блок календаря$/, "Встреча пересекается с вашим защищённым временем"],
  [/^Сумма не извлечена$/, "Не смогла определить сумму"],
  [/^Режим тени$/, "Включён режим тени: сначала показываю вам всё"],
  [/^Режим обучения/, "Я пока учусь: без вашего «да» ничего не отправляю"],
  [/^Инструмент .+ требует подтверждения$/, "Это действие во внешнем сервисе по умолчанию идёт через вас"],
  [/^Инструмент .+ запрещён$/, "Вы запретили это действие"],
  [/^Применено правило$/, "Сработало ваше правило"],
];

function humanizeOne(reason: string): string[] {
  const sig = /^Жёсткие сигналы(?: риска)?: (.+)$/.exec(reason);
  if (sig) {
    return sig[1]
      .split(",")
      .map((s) => s.trim())
      .filter(Boolean)
      .map((code) => SIGNALS[code] ?? code);
  }
  const cat = /^Защищённая категория (\w+)$/.exec(reason);
  if (cat) return [CATEGORIES[cat[1]] ?? "Эту тему я без вас не решаю"];

  const amount = /^Сумма (.+) ₽ выше порога автоответа (.+) ₽$/.exec(reason);
  if (amount) return [`Сумма ${amount[1]} ₽ выше вашего порога автоответа (${amount[2]} ₽)`];

  for (const [re, text] of EXACT) if (re.test(reason)) return [text];
  return [reason]; // неизвестное — как есть, но не теряем
}

/** Человеческие причины без повторов, порядок сохраняется. */
export function humanizeReasons(reasons: readonly string[]): string[] {
  const out: string[] = [];
  for (const r of reasons) for (const h of humanizeOne(r)) if (!out.includes(h)) out.push(h);
  return out;
}
